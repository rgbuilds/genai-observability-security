from __future__ import annotations

from typing import Any, Literal

Role = Literal["case", "control"]
Source = Literal["scripted", "mocked-capture"]

FAMILIES: tuple[str, ...] = ("F1", "F2", "F3", "F4", "F5", "F6")


def _plant(token: str, location: str, payload_field: str) -> dict[str, str]:
    return {"token": token, "location": location, "payload_field": payload_field}


def _execution(
    *,
    pair_id: str,
    family: str,
    source: Source,
    role: Role,
    user: str,
    output: str,
    system: str | None = None,
    principal: str = "principal-member",
    roles: list[str] | None = None,
    resource: str | None = None,
    retrieval_id: str | None = None,
    retrieval_body: str | None = None,
    tool_name: str | None = None,
    tool_args: dict[str, Any] | None = None,
    tool_result: dict[str, Any] | None = None,
    allowed: bool | None = None,
    canaries: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    execution_id = f"fs-{pair_id.lower()}-{role[:4] if role == 'case' else 'ctrl'}"
    privilege = None
    denial = None
    if tool_name == "delete_account":
        privilege = "privileged"
        denial = "none" if allowed else "authorization"
    elif tool_name == "get_note":
        privilege = "none"
        denial = "none"
    return {
        "execution_id": execution_id,
        "pair_id": pair_id,
        "family": family,
        "intended_family": family,
        "role": role,
        "source": source,
        "user": user,
        "system": system,
        "output": output,
        "principal": principal,
        "roles": roles or ["member"],
        "resource": resource,
        "retrieval_id": retrieval_id,
        "retrieval_body": retrieval_body,
        "tool_name": tool_name,
        "tool_args": tool_args,
        "tool_result": tool_result,
        "allowed": allowed,
        "privilege": privilege,
        "denial_reason": denial,
        "canaries": canaries or [],
    }


